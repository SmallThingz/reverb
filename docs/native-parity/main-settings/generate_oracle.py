#!/usr/bin/env python3
"""Generate the unchanged release MainScreen entry; refuse an unreviewed source revision."""
from pathlib import Path
import hashlib
import json
import sys
import subprocess

out = Path(__file__).resolve().parent
project = out.parents[2]
source = Path(sys.argv[1]) if len(sys.argv) > 1 else None
text = source.read_text() if source else subprocess.check_output(
    ["git", "show", "3e16f8d:app/src/main/java/app/smallthingz/reverb/MainActivity.kt"], cwd=project, text=True)
source_hash = hashlib.sha256(text.encode()).hexdigest()
assert source_hash == "700410262137f40c16c327cc040b64f53de05ceebd8b14b9dd4d18f48cde5c15", source_hash
marker = "@OptIn(ExperimentalMaterial3Api::class)\n@Composable\nprivate fun MainScreen("
assert text.count(marker) == 1
body = text[text.index(marker):]
assert hashlib.sha256(body.encode()).hexdigest() == "21ff9d00cdf3e42955c1c93f51959cb3541f052de2aff5ca89b716f157aaf421"
replacements = [
    ("private fun MainScreen(", "internal fun ReleasedMainScreenParityOracle("),
    ("MainPanelDragTarget", "MainParityOracleDragTarget"),
    ("PANEL_SETTLE_DURATION_MS", "MAIN_PARITY_ORACLE_SETTLE_DURATION_MS"),
]
renamed = body
for before, after in replacements:
    renamed = renamed.replace(before, after)
imports = "\n".join(line for line in text.splitlines() if line.startswith("import "))
oracle = """// Mechanically extracted release MainScreen; generated by generate_oracle.py.
// No body/state/geometry/input substitutions. Entry and file-private symbols are renamed only.
package app.smallthingz.reverb

""" + imports + "\n\nprivate const val MAIN_PARITY_ORACLE_SETTLE_DURATION_MS = 220\nprivate enum class MainParityOracleDragTarget { SETTINGS, LIBRARY }\n\n" + renamed
assert hashlib.sha256(oracle.encode()).hexdigest() == "614856c6ad8a0a54027c932d44f1361003e73f1bf7faafaf7b902e9e8c6d117f"
(out / "ReleasedMainScreenParityOracle.kt").write_text(oracle)
print(json.dumps({"source_sha256": source_hash, "oracle_sha256": hashlib.sha256(oracle.encode()).hexdigest()}))
